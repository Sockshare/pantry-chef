def format_quantity(val: float) -> str:
    """Format a floating point quantity into clean culinary fractions (e.g., 1.25 -> '1 ¼', 0.5 -> '½')."""
    if val <= 0:
        return "a pinch"
    whole = int(math.floor(val + 1e-6))
    rem = val - whole
    if rem < 0.06:
        return str(whole) if whole > 0 else "⅛"
    if rem > 0.93:
        return str(whole + 1)
    best_sym = ""
    best_diff = 1.0
    for target, sym in _FRACTION_TABLE:
        diff = abs(rem - target)
        if diff < best_diff:
            best_diff = diff
            best_sym = sym
    if whole == 0:
        return best_sym
    return f"{whole} {best_sym}"


