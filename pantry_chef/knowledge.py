def evaluate_recipe(
    recipe: dict[str, Any],
    pantry_items: list[dict[str, str]],
    servings: int = 2,
) -> dict[str, Any]:
    """Compute Waste-Saver Score %, Pantry Match %, matched/missing counts, substitutions, scaled quantities, and extracted timers."""
    pantry_urgency_map: dict[str, str] = {item["id"]: item.get("urgency", "fresh") for item in pantry_items if item.get("id")}
    pantry_ids: set[str] = set(pantry_urgency_map.keys())

    urgent_in_pantry = {iid for iid, urg in pantry_urgency_map.items() if urg == "urgent"}
    soon_in_pantry = {iid for iid, urg in pantry_urgency_map.items() if urg == "soon"}

    recipe_ings = recipe["ingredients"]
    total_ings = max(1, len(recipe_ings))

    in_pantry_count = 0
    sub_available_count = 0
    rescued_urgent: list[str] = []
    rescued_soon: list[str] = []
    matched_ingredient_ids: list[str] = []
    matched_ingredient_names: list[str] = []
    waste_saved_dollars = 0.0

    detailed_ingredients: list[dict[str, Any]] = []
    substitutions_used: list[dict[str, Any]] = []
    missing_items: list[dict[str, Any]] = []

    for ing in recipe_ings:
        iid = ing["id"]
        meta = INGREDIENT_MAP.get(
            iid,
            {"id": iid, "name": iid.replace("_", " ").title(), "emoji": "🥘", "category": "Fresh Produce — Vegetables", "aisle": "Produce", "cost_est": 1.0},
        )
        scaled_display = scale_amount(float(ing["qty"]), ing["unit"], int(recipe["base_servings"]), servings)

        if iid in pantry_ids:
            urg = pantry_urgency_map[iid]
            in_pantry_count += 1
            matched_ingredient_ids.append(iid)
            matched_ingredient_names.append(meta["name"])
            if urg == "urgent":
                rescued_urgent.append(meta["name"])
                waste_saved_dollars += float(meta.get("cost_est", 1.25)) * 1.4
            elif urg == "soon":
                rescued_soon.append(meta["name"])
                waste_saved_dollars += float(meta.get("cost_est", 1.0)) * 0.9
            else:
                waste_saved_dollars += float(meta.get("cost_est", 0.75)) * 0.35

            detailed_ingredients.append(
                {
                    "id": iid,
                    "name": meta["name"],
                    "emoji": meta["emoji"],
                    "aisle": meta["aisle"],
                    "role": ing.get("role", ""),
                    "scaled_amount": scaled_display,
                    "status": "in_pantry",
                    "urgency": urg,
                    "urgency_label": URGENCY_META.get(urg, URGENCY_META["fresh"])["label"],
                    "substitution": None,
                }
            )
        else:
            sub = find_substitution(iid, pantry_ids)
            if sub and sub.get("in_pantry"):
                sub_available_count += 1
                substitutions_used.append(sub)
                detailed_ingredients.append(
                    {
                        "id": iid,
                        "name": meta["name"],
                        "emoji": meta["emoji"],
                        "aisle": meta["aisle"],
                        "role": ing.get("role", ""),
                        "scaled_amount": scaled_display,
                        "status": "sub_available",
                        "urgency": None,
                        "urgency_label": "Chemistry Sub Ready",
                        "substitution": sub,
                    }
                )
            else:
                if sub:
                    substitutions_used.append(sub)
                missing_items.append(
                    {
                        "id": iid,
                        "name": meta["name"],
                        "emoji": meta["emoji"],
                        "aisle": meta["aisle"],
                        "scaled_amount": scaled_display,
                        "cost_est": round(float(meta.get("cost_est", 1.0)) * (servings / max(1, recipe["base_servings"])), 2),
                    }
                )
                detailed_ingredients.append(
                    {
                        "id": iid,
                        "name": meta["name"],
                        "emoji": meta["emoji"],
                        "aisle": meta["aisle"],
                        "role": ing.get("role", ""),
                        "scaled_amount": scaled_display,
                        "status": "missing",
                        "urgency": None,
                        "urgency_label": "Need to Buy / Sub",
                        "substitution": sub,
                    }
                )

    effective_matches = in_pantry_count + (0.85 * sub_available_count)
    pantry_match_pct = min(100, int(round((effective_matches / total_ings) * 100)))

    if urgent_in_pantry or soon_in_pantry:
        max_possible_urgency_points = len(urgent_in_pantry) * 3.2 + len(soon_in_pantry) * 1.8
        achieved_urgency_points = len(rescued_urgent) * 3.2 + len(rescued_soon) * 1.8
        raw_waste_ratio = min(1.0, achieved_urgency_points / max(1.0, min(max_possible_urgency_points, 9.5)))
        waste_saver_score = min(100, int(round(raw_waste_ratio * 78 + (pantry_match_pct * 0.22))))
    else:
        waste_saver_score = pantry_match_pct

    combined_rank_score = round((pantry_match_pct * 0.55) + (waste_saver_score * 0.45), 1)
    timers = extract_timers_from_steps(recipe["steps"])
    missing_count = len(missing_items)
    is_ready_now = (missing_count == 0) and (in_pantry_count >= 1)

    return {
        **recipe,
        "servings": servings,
        "matched_count": in_pantry_count,
        "sub_available_count": sub_available_count,
        "missing_count": missing_count,
        "total_ingredients": total_ings,
        "is_ready_now": is_ready_now,
        "matched_ingredient_ids": matched_ingredient_ids,
        "matched_ingredient_names": matched_ingredient_names,
        "pantry_match_pct": pantry_match_pct,
        "waste_saver_score": waste_saver_score,
        "combined_rank_score": combined_rank_score,
        "rescued_urgent": rescued_urgent,
        "rescued_soon": rescued_soon,
        "waste_saved_dollars": round(max(1.25, waste_saved_dollars * (servings / max(1, recipe["base_servings"]))), 2) if in_pantry_count > 0 else 0.0,
        "ingredients_detail": detailed_ingredients,
        "substitutions": substitutions_used,
        "missing_items": missing_items,
        "timers": timers,
    }


def rank_and_synthesize_recipes(
    pantry_items: list[dict[str, str]],
    filters: list[str] | None = None,
    servings: int = 2,
    browse_all: bool = False,
) -> list[dict[str, Any]]:
    """Auto-populate and rank ONLY recipes that use at least 1 selected ingredient.

    If `pantry_items` is empty and `browse_all` is False, strictly returns `[]` (zero default meals).
    """
    valid_pantry = [item for item in (pantry_items or []) if item.get("id")]
    if not valid_pantry and not browse_all:
        return []

    active_filters = [f for f in (filters or []) if f]
    tag_filters = [f for f in active_filters if f not in ("ready_now", "missing_1_2", "under_20_min")]
    want_ready_now = "ready_now" in active_filters
    want_missing_1_2 = "missing_1_2" in active_filters
    want_under_20 = "under_20_min" in active_filters

    candidates: list[dict[str, Any]] = []

    for r in RECIPES:
        if tag_filters:
            if not all(f in r.get("tags", []) for f in tag_filters):
                continue
        if want_under_20 and int(r.get("prep_minutes", 30)) > 20:
            continue

        evaluated = evaluate_recipe(r, valid_pantry, servings=servings)

        # Strict rule: never include recipes with 0 overlap with the user's selected ingredients
        if not browse_all and evaluated["matched_count"] < 1:
            continue

        if want_ready_now and not (evaluated["is_ready_now"] or evaluated["missing_count"] <= 1):
            continue
        if want_missing_1_2 and not (0 <= evaluated["missing_count"] <= 2):
            continue

        candidates.append(evaluated)

    # Intelligent ranking:
    # 1. Ready to Cook Now (100% matched or subbed)
    # 2. Highest Pantry Match % and Matched Ingredient Count
    # 3. Expiring Soon ("Use Today!") rescues & Waste-Saver Score
    # 4. Substitutable matches & fewest missing items
    candidates.sort(
        key=lambda x: (
            1 if x["is_ready_now"] else 0,
            x["pantry_match_pct"],
            x["matched_count"],
            len(x["rescued_urgent"]),
            x["sub_available_count"],
            x["waste_saver_score"],
            -x["missing_count"],
        ),
        reverse=True,
    )
    return candidates


def build_grocery_list(
    recipe_ids: list[str],
    pantry_items: list[dict[str, str]],
    servings: int = 2,
) -> dict[str, Any]:
    """Aggregate missing ingredients across selected recipes, grouped by Supermarket Aisle."""
    recipe_lookup = {r["id"]: r for r in RECIPES}
    aisles: dict[str, list[dict[str, Any]]] = {}
    seen_ids: set[str] = set()
    total_est_cost = 0.0
    selected_titles: list[str] = []

    for rid in recipe_ids:
        r = recipe_lookup.get(rid)
        if not r and rid == "custom_alchemist_skillet":
            r = _synthesize_custom_alchemist_recipe(pantry_items, [])
        if not r:
            continue
        selected_titles.append(r["title"])
        evaluated = evaluate_recipe(r, pantry_items, servings=servings)
        for m in evaluated["missing_items"]:
            if m["id"] in seen_ids:
                continue
            seen_ids.add(m["id"])
            aisle = m["aisle"]
            aisles.setdefault(aisle, []).append(m)
            total_est_cost += float(m["cost_est"])

    lines = [
        f"# 🛒 Pantry Chef — Smart Grocery & Meal-Prep List ({servings} Servings)",
        f"**Planned Meals:** {', '.join(selected_titles) if selected_titles else 'None Selected Yet'}",
        "",
    ]
    if not selected_titles:
        lines.append("Select ingredients in your Pantry to auto-populate meals, then add meals to your Grocery Plan!")
    elif not aisles:
        lines.append("✅ **Zero Missing Items!** Your fridge & chemistry substitutions cover 100% of this meal plan.")
    else:
        for aisle_name, items in sorted(aisles.items()):
            lines.append(f"### 🏪 {aisle_name}")
            for item in items:
                lines.append(f"- [ ] {item['emoji']} **{item['name']}** — {item['scaled_amount']} *(~${item['cost_est']:.2f})*")
            lines.append("")
        lines.append(f"**Estimated Grocery Spend:** ${total_est_cost:.2f}")

    return {
        "servings": servings,
        "planned_recipes": selected_titles,
        "aisles": aisles,
        "total_missing_count": len(seen_ids),
        "total_estimated_cost": round(total_est_cost, 2),
        "markdown": "\n".join(lines),
    }


def validate() -> list[str]:
    """Self-check validator for knowledge integrity."""
    errors: list[str] = []
    if len(INGREDIENTS) < 100:
        errors.append(f"Expected at least 100 curated ingredients, got {len(INGREDIENTS)}")
    if len(PRESETS) < 5:
        errors.append("Expected at least 5 quick presets")
    if len(RECIPES) < 75:
        errors.append(f"Expected at least 75 curated chef recipes, got {len(RECIPES)}")
    for r in RECIPES:
        timers = extract_timers_from_steps(r["steps"])
        if not timers:
            errors.append(f"Recipe {r['id']} has no extractable step timers")
        for ing in r["ingredients"]:
            if ing["id"] not in INGREDIENT_MAP:
                errors.append(f"Recipe {r['id']} references unknown ingredient '{ing['id']}'")
    return errors
