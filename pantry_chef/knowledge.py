_TIMER_PATTERN = re.compile(
    r"\b(?:for|about|another|around)?\s*(\d+(?:\.\d+)?)\s*(?:to\s*(\d+(?:\.\d+)?)\s*)?(minutes?|mins?|seconds?|secs?|hours?|hrs?)\b",
    re.IGNORECASE,
)


def extract_timers_from_steps(steps: list[dict[str, Any]]) -> list[dict[str, Any]]:
    """Automatically extract every time duration from recipe steps into actionable live countdown timers."""
    timers: list[dict[str, Any]] = []
    for idx, step in enumerate(steps):
        text = step.get("instruction", "")
        step_title = step.get("title", f"Step {idx + 1}")
        for match in _TIMER_PATTERN.finditer(text):
            low_val = float(match.group(1))
            unit_raw = match.group(3).lower()
            val = low_val
            if unit_raw.startswith("hour") or unit_raw.startswith("hr"):
                seconds = int(round(val * 3600))
                display_dur = f"{int(val * 60)} min"
            elif unit_raw.startswith("sec"):
                seconds = int(round(val))
                display_dur = f"{seconds} sec"
            else:
                seconds = int(round(val * 60))
                display_dur = f"{int(val) if val.is_integer() else val} min"

            prefix = text[: match.start()].strip()
            verb_match = re.findall(
                r"\b(sear|simmer|boil|bake|roast|rest|whisk|sauté|steam|char|fry|cook|crispen|marinate|steep|poach|broil|toast)\b",
                prefix,
                re.IGNORECASE,
            )
            action_verb = verb_match[-1].capitalize() if verb_match else step_title
            timer_id = f"step-{idx + 1}-timer-{len(timers) + 1}"
            timers.append(
                {
                    "id": timer_id,
                    "step_index": idx,
                    "step_number": idx + 1,
                    "label": f"{action_verb} ({display_dur})",
                    "duration_seconds": seconds,
                    "display_duration": display_dur,
                    "matched_phrase": match.group(0).strip(),
                }
            )
    return timers


